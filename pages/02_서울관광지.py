# -----------------------------
# 지도 생성
# -----------------------------
seoul_center = [37.5665, 126.9780]

m = folium.Map(
    location=seoul_center,
    zoom_start=11,
    tiles="OpenStreetMap"
)

# 마커 추가
for idx, (name, info) in enumerate(places.items(), start=1):

    popup_html = f"""
    <b>{idx}. {name}</b><br>
    {info['desc']}
    """

    folium.Marker(
        location=[info["lat"], info["lon"]],
        popup=popup_html,
        tooltip=name,
        icon=folium.Icon(color="red", icon="info-sign")
    ).add_to(m)

# -----------------------------
# 지도 출력 (80% 크기)
# -----------------------------
